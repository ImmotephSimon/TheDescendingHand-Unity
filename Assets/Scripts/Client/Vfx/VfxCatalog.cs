using System;
using System.Collections.Generic;
using UnityEngine;

[CreateAssetMenu(menuName = "Registries/Vfx")]
public class VfxCatalog : ScriptableObject
{
    [SerializeField] private List<VfxEntry> entries = new();

    private Dictionary<GameObject, VfxString> _prefabToId;
    private Dictionary<VfxString, GameObject> _idToPrefab;
    private static VfxCatalog _instance;
    private static bool _loadAttempted;


    public static VfxCatalog Instance
    {
        get
        {
            if (_instance != null)
                return _instance;

            if (_loadAttempted)
                return null;

            _loadAttempted = true;
            _instance = Resources.Load<VfxCatalog>("VfxCatalog");

            if (_instance == null)
                Debug.LogError("VfxCatalog not found at Resources/VfxCatalog.asset.");

            return _instance;
        }
    }

    private void EnsureInit()
    {
        if (_prefabToId != null)
            return;

        _prefabToId = new();
        _idToPrefab = new();

        foreach (VfxEntry entry in entries)
        {
            if (entry.Prefab == null)
            {
                Debug.LogError("[VfxCatalog] Entry has a missing prefab.", this);
                continue;
            }

            if (entry.Id.IsEmpty)
            {
                Debug.LogError($"[VfxCatalog] Entry for prefab '{entry.Prefab.name}' has a missing ID.", this);
                continue;
            }

            _prefabToId[entry.Prefab] = entry.Id;
            _idToPrefab[entry.Id] = entry.Prefab;
        }
    }

    public bool TryGetId(GameObject prefab, out VfxString id)
    {
        EnsureInit();

        if (_prefabToId.TryGetValue(prefab, out id))
            return true;

        Debug.LogError(
            $"[VfxRegistry] No ID registered for prefab '{prefab?.name}'.");
        return false;
    }

    public bool TryGetPrefab(VfxString id, out GameObject prefab)
    {
        EnsureInit();

        if (_idToPrefab.TryGetValue(id, out prefab))
            return true;

        Debug.LogError(
            $"[VfxRegistry] No prefab registered for ID '{id}'.");
        return false;
    }

#if UNITY_EDITOR
    // IDs are generated by CatalogAssetIndex from asset GUID + local file ID.
    // Do not generate or modify IDs in the catalog; VfxCatalogGenerator owns entry generation.

    private void OnValidate()
    {
        _prefabToId = null;
        _idToPrefab = null;
    }

    public bool SetGeneratedEntries(List<VfxEntry> newEntries)
    {
        if (entries.Count == newEntries.Count)
        {
            bool same = true;
            for (int i = 0; i < entries.Count; i++)
            {
                if (!entries[i].Id.Equals(newEntries[i].Id) || entries[i].Prefab != newEntries[i].Prefab)
                {
                    same = false;
                    break;
                }
            }
            if (same) return false;
        }

        entries = new List<VfxEntry>(newEntries);
        _prefabToId = null;
        _idToPrefab = null;
        return true;
    }
#endif
}

[Serializable]
public struct VfxEntry
{
    [SerializeField, HideInInspector] private VfxString id;
    [SerializeField] private GameObject prefab;

    public readonly VfxString Id => id;
    public readonly GameObject Prefab => prefab;

    public VfxEntry(VfxString id, GameObject prefab)
    {
        this.id = id;
        this.prefab = prefab;
    }
}